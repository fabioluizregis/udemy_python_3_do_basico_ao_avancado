""""
Python = Linguagem de Programação
Tipo de Tipagem = Dinâmica / Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
"""

# Aspas Simples
print('Fabio Luiz')
print('Fabio "Luiz"')
# Aspas Duplas
print("Fabio Luiz")
print("Fabio 'Luiz'")
# Escape
print("Fabio \"Luiz\"")
# r -> raw string -> string crua
print(r"Fabio \"Luiz\"")
