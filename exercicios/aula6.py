# Conversão de tipos, coerção, type convertion,
# typecasting, coercion. É o ato de converter 
# um tipo em outros tipos imutáveise primitivos.
# str, int, float, bool

print(int('1'), type(int('1')))
print(int('1') + 1)
print(float('1') + 1)
print(bool(''))        # String vazia = False
print(bool('XPTO'))     # String com qualquer coisa dentro = True
print(str(11) + 'b')